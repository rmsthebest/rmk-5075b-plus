#!/usr/bin/env python3
"""Generate lighting/src/layout.rs from the QMK board's keyboard.json.

    python3 -I tools/gen_leds.py [qmk-keyboard-dir] > lighting/src/layout.rs

rgb_matrix.layout, in chain order: each LED's position (x 0-224, y 0-64),
its flags, and its matrix position if it has one. Also the matrix -> LED
table QMK builds from it (g_led_config.matrix_co), and the centre QMK's
effects measure from (k_rgb_matrix_center: QMK's default {112, 32}, as the
board defines no RGB_MATRIX_CENTER).
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
QMK_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "../../qmk_5075b_plus/keyboards/akko/5075b_plus")

j = json.load(open(os.path.join(QMK_DIR, "keyboard.json")))
leds = j["rgb_matrix"]["layout"]
rows, cols = 6, 15
matrix_co = [[None] * cols for _ in range(rows)]
for i, l in enumerate(leds):
    if "matrix" in l:
        r, c = l["matrix"]
        matrix_co[r][c] = i
cx, cy = 112, 32

out = []
out.append("// Generated by tools/gen_leds.py from the QMK board's keyboard.json")
out.append("// (rgb_matrix.layout). Don't edit; rerun it.")
out.append("")
out.append(f"pub const LED_COUNT: usize = {len(leds)};")
out.append(f"pub const MATRIX_ROWS: usize = {rows};")
out.append(f"pub const MATRIX_COLS: usize = {cols};")
out.append("/// QMK's NO_LED.")
out.append("pub const NO_LED: u8 = 255;")
out.append("")
out.append("/// k_rgb_matrix_center.")
out.append(f"pub const CENTER: (u8, u8) = ({cx}, {cy});")
out.append("")
out.append("/// Position (x, y) of each LED, in chain order.")
out.append("#[rustfmt::skip]")
out.append(f"pub const POINTS: [(u8, u8); LED_COUNT] = [")
for i in range(0, len(leds), 8):
    out.append("    " + " ".join(f"({l['x']}, {l['y']})," for l in leds[i:i + 8]))
out.append("];")
out.append("")
out.append("/// Flags of each LED (QMK LED_FLAG_*: 4 = keylight).")
out.append("#[rustfmt::skip]")
out.append(f"pub const FLAGS: [u8; LED_COUNT] = [")
for i in range(0, len(leds), 16):
    out.append("    " + " ".join(f"{l['flags']}," for l in leds[i:i + 16]))
out.append("];")
out.append("")
out.append("/// LED under each matrix position (g_led_config.matrix_co), NO_LED if none.")
out.append("#[rustfmt::skip]")
out.append(f"pub const MATRIX_CO: [[u8; MATRIX_COLS]; MATRIX_ROWS] = [")
for r in range(rows):
    out.append("    [" + ", ".join("NO_LED" if v is None else str(v) for v in matrix_co[r]) + "],")
out.append("];")
print("\n".join(out))
